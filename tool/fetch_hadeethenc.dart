// Fetches translations of the daily hadith from HadeethEnc.com into
// tool/daily/translations/hadeethenc_<language>.json, which
// tool/build_daily_content.dart then bundles. The app itself never calls the
// API: everything ships offline.
//
// Usage (from the quran_app directory):
//   dart run tool/fetch_hadeethenc.dart [language=ur]
//
// HadeethEnc's terms: content is used without modification, addition or
// deletion, and HadeethEnc.com is credited as publisher and source. Text is
// stored exactly as the API returns it (trimmed of surrounding whitespace).
//
// A HadeethEnc entry is accepted for one of our hadith only if BOTH:
//   1. its reference cites the same hadith number in the same book
//      (sunnah.com's Bukhari numbers, and Muslim's Fuad Abdul-Baqi numbers,
//      which sunnah.com's Muslim numbers are based on); and
//   2. its Arabic matn has exactly the same words as ours, once diacritics,
//      letter variants and punctuation are folded away (see
//      [matnSimilarity]).
// Without (2), a translation of another narration of the same hadith could be
// shown under Arabic and English that say something slightly different.
//
// API responses are cached in tool/cache/hadeethenc/ (git-ignored), so a
// re-run is offline and deterministic.

import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;
import 'package:quran_app/core/text/normalize.dart';

const _api = 'https://hadeethenc.com/api/v1';
const _cacheDir = 'tool/cache/hadeethenc';
const _contentPath = 'assets/daily/daily_content.json';
const _source = 'HadeethEnc.com';

Future<void> main(List<String> args) async {
  if (!File('pubspec.yaml').existsSync()) {
    stderr.writeln('Run this from the quran_app directory.');
    exitCode = 64;
    return;
  }
  final language = args.isNotEmpty ? args.first : 'ur';
  final api = _CachedApi(http.Client());
  try {
    // Our hadith, as bundled (sunnah.com Arabic matn).
    final content =
        jsonDecode(File(_contentPath).readAsStringSync())
            as Map<String, Object?>;
    final ours = [
      for (final h in content['hadiths']! as List)
        (
          ref: '${(h as Map)['collection']}:${h['number']}',
          arabic: h['arabic'] as String,
        ),
    ];

    final ids = await api.allIds();
    stdout.writeln('HadeethEnc lists ${ids.length} hadith.');
    final arabic = await api.records('ar', ids);

    final matches = <String, String>{}; // our ref -> HadeethEnc id
    final report = <String>[];
    for (final hadith in ours) {
      final cited = [
        for (final record in arabic.values)
          if (citesHadith(record['reference'] as String? ?? '', hadith.ref))
            record,
      ];
      if (cited.isEmpty) {
        report.add('${hadith.ref}: not in HadeethEnc');
        continue;
      }
      final scored = [
        for (final record in cited)
          (
            id: record['id'] as String,
            score: matnSimilarity(hadith.arabic, record['hadeeth'] as String),
          ),
      ]..sort((a, b) => b.score.compareTo(a.score));
      final best = scored.first;
      if (best.score == 1) {
        matches[hadith.ref] = best.id;
      } else {
        report.add(
          '${hadith.ref}: HadeethEnc ${best.id} cites it, but its wording '
          'differs (${(best.score * 100).round()}% alike)',
        );
      }
    }

    final translated = await api.records(language, matches.values.toSet());
    final output = <String, Object?>{};
    for (final MapEntry(key: ref, value: id) in matches.entries) {
      final record = translated[id];
      final text = (record?['hadeeth'] as String?)?.trim() ?? '';
      if (text.isEmpty) {
        report.add('$ref: HadeethEnc $id has no "$language" translation');
        continue;
      }
      output[ref] = {'id': id, 'text': text};
    }

    final file = File('tool/daily/translations/hadeethenc_$language.json');
    await file.parent.create(recursive: true);
    await file.writeAsString(
      '${const JsonEncoder.withIndent('  ').convert({r'$comment': 'Generated by tool/fetch_hadeethenc.dart. Do not edit: '
          'HadeethEnc content must be used unmodified.', 'source': _source, 'language': language, 'hadiths': output})}\n',
    );
    stdout
      ..writeln('Matched ${output.length} of ${ours.length} hadith.')
      ..writeln('Wrote ${file.path}.');
    if (report.isNotEmpty) {
      stdout
        ..writeln('Left without a "$language" translation:')
        ..writeAll(report.map((r) => '  - $r'), '\n')
        ..writeln();
    }
  } finally {
    api.close();
  }
}

/// True when a HadeethEnc `reference` cites [ref] ("bukhari:6114",
/// "muslim:2564c"): a line naming the book whose parenthesised hadith
/// number equals ours (the letter of a Muslim sub-narration is ignored).
bool citesHadith(String reference, String ref) {
  final [collection, number] = ref.split(':');
  final book = switch (collection) {
    'bukhari' => 'صحيح البخاري',
    'muslim' => 'صحيح مسلم',
    _ => throw ArgumentError(ref),
  };
  final wanted = RegExp(r'^\d+').stringMatch(number);
  for (final line in reference.split('\n')) {
    if (!line.contains(book)) continue;
    // "صحيح البخاري (9/ 2) (6864)." — the last parentheses hold the number.
    final groups = RegExp(r'\(([^)]*)\)').allMatches(line).toList();
    if (groups.isEmpty) continue;
    final numbers = RegExp(r'\d+').allMatches(groups.last.group(1)!);
    if (numbers.any((m) => m.group(0) == wanted)) return true;
  }
  return false;
}

/// How alike two Arabic texts are, 0–1: the longest common run of words
/// relative to their combined length, after diacritics, letter variants and
/// punctuation are folded away. HadeethEnc quotes the Prophet's words in
/// «guillemets», after the narrator; only the quoted words are compared when
/// present.
double matnSimilarity(String ours, String theirs) {
  final a = _words(ours);
  final b = _words(_quotedMatn(theirs));
  if (a.isEmpty || b.isEmpty) return 0;
  return 2 * _lcs(a, b) / (a.length + b.length);
}

String _quotedMatn(String text) {
  final quoted = RegExp('«([^»]*)»').allMatches(text).map((m) => m.group(1));
  return quoted.isEmpty ? text : quoted.join(' ');
}

List<String> _words(String text) =>
    normalizeForSearch(text).split(' ').where((w) => w.isNotEmpty).toList();

int _lcs(List<String> a, List<String> b) {
  var previous = List.filled(b.length + 1, 0);
  for (final word in a) {
    final row = List.filled(b.length + 1, 0);
    for (var j = 0; j < b.length; j++) {
      row[j + 1] = word == b[j]
          ? previous[j] + 1
          : (row[j] > previous[j + 1] ? row[j] : previous[j + 1]);
    }
    previous = row;
  }
  return previous.last;
}

/// A short, stable file name for a request path (64-bit FNV-1a, hex).
String _fnv1a(String text) {
  var hash = 0xcbf29ce484222325;
  for (final byte in utf8.encode(text)) {
    hash = (hash ^ byte) * 0x100000001b3;
  }
  return hash.toUnsigned(64).toRadixString(16).padLeft(16, '0');
}

/// The HadeethEnc API, with every response cached on disk.
class _CachedApi {
  _CachedApi(this._client);

  final http.Client _client;

  static const _rootCategories = 'categories/roots';
  static const _pageSize = 100;
  static const _batchSize = 40;

  void close() => _client.close();

  /// Every hadith id, from the root categories (which include their
  /// sub-categories).
  Future<Set<String>> allIds() async {
    final roots = await _get('$_rootCategories/?language=ar') as List;
    final ids = <String>{};
    for (final root in roots) {
      final category = (root as Map)['id'];
      for (var page = 1; ; page++) {
        final body =
            await _get(
                  'hadeeths/list/?language=ar&category_id=$category'
                  '&page=$page&per_page=$_pageSize',
                )
                as Map;
        for (final item in body['data'] as List) {
          ids.add((item as Map)['id'] as String);
        }
        final meta = body['meta'] as Map;
        if (page >= (meta['last_page'] as num)) break;
      }
    }
    return ids;
  }

  /// Full records in [language], keyed by id.
  Future<Map<String, Map<String, Object?>>> records(
    String language,
    Iterable<String> ids,
  ) async {
    final sorted = ids.toList()..sort((a, b) => int.parse(a) - int.parse(b));
    final result = <String, Map<String, Object?>>{};
    for (var i = 0; i < sorted.length; i += _batchSize) {
      final batch = sorted.skip(i).take(_batchSize).join(',');
      final body = await _get(
        'hadeeths/multiple/?language=$language&ids=$batch',
      );
      for (final record in body is List ? body : const []) {
        final map = (record as Map).cast<String, Object?>();
        result[map['id']! as String] = map;
      }
      stdout.write('\r  $language: ${result.length}/${sorted.length}');
    }
    stdout.writeln();
    return result;
  }

  Future<Object?> _get(String path) async {
    final cache = File('$_cacheDir/${_fnv1a(path)}.json');
    if (cache.existsSync()) return jsonDecode(await cache.readAsString());

    final response = await _client.get(
      Uri.parse('$_api/$path'),
      headers: {'User-Agent': 'quran-app-build-tool'},
    );
    if (response.statusCode != 200) {
      throw HttpException('${response.statusCode} for $path');
    }
    final body = utf8.decode(response.bodyBytes);
    final decoded = jsonDecode(body);
    await cache.parent.create(recursive: true);
    await cache.writeAsString(body);
    // Be gentle with a free, volunteer-run service.
    await Future<void>.delayed(const Duration(milliseconds: 150));
    return decoded;
  }
}
